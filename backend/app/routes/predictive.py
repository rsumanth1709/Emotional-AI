"""
MindCare AI — Predictive AI Forecasting Routes
"""
from typing import Annotated
from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session

from app.database import get_db
from app.models.user import User
from app.schemas.chat import PredictiveForecastResponse
from app.services.predictive_service import predictive_service
from app.utils.security import get_current_active_user

router = APIRouter(prefix="/predictive", tags=["Predictive AI"])

DBDep = Annotated[Session, Depends(get_db)]
CurrentUser = Annotated[User, Depends(get_current_active_user)]


@router.get("/forecast", response_model=PredictiveForecastResponse)
def get_mood_forecast(current_user: CurrentUser, db: DBDep):
    """
    Fetch tomorrow's predicted mood, stress probability, 7-day forecast,
    and 95% confidence intervals generated by PyTorch MoodLSTM model.
    """
    return predictive_service.get_user_forecast(db=db, user_id=current_user.id)


@router.post("/retrain")
def retrain_predictive_model(current_user: CurrentUser):
    """Trigger on-demand training of the PyTorch MoodLSTM sequence model."""
    try:
        import sys
        import os
        # Ensure project root is in sys.path
        route_dir = os.path.dirname(os.path.abspath(__file__))
        app_dir = os.path.dirname(route_dir)
        backend_dir = os.path.dirname(app_dir)
        project_root = os.path.dirname(backend_dir)

        if project_root not in sys.path:
            sys.path.insert(0, project_root)
        if backend_dir not in sys.path:
            sys.path.insert(0, backend_dir)

        from ai.train_mood_lstm import train_model
        train_model()

        # Reload updated model weights in lstm_forecaster singleton
        from app.ai.lstm_forecaster import lstm_forecaster
        lstm_forecaster._load_model()

        return {"status": "success", "message": "PyTorch MoodLSTM model retrained successfully."}
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Model retraining failed: {str(e)}")
